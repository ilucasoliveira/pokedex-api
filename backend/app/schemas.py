class UserCreate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={"examples": [{"username": "ash", "password": "pikachu123"}]}
    )

    username: str = Field(
        min_length=3,
        max_length=50,
        description="Unique username. Stored in lowercase.",
    )
    password: str = Field(
        min_length=8,
        max_length=72,
        description="Password between 8 characters and 72 bytes (bcrypt limit).",
    )

    @field_validator("username", mode="after")
    @classmethod
    def padronizar_username(cls, value: str) -> str:
        return value.lower()

    @field_validator("password", mode="after")
    @classmethod
    def validar_tamanho_em_bytes(cls, value: str) -> str:
        if len(value.encode()) > 72:
            raise ValueError("Password must be at most 72 bytes.")
        return value


