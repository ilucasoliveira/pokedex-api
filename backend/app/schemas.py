class ErrorResponse(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={"examples": [{"detail": "Pokémon not found"}]}
    )

    detail: str = Field(description="Human-readable error message.")


class UserCreate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={"examples": [{"username": "ash", "password": "pikachu123"}]}
    )

    username: str = Field(
        min_length=3,
        max_length=50,
        description="Unique username. Stored in lowercase.",
    )
    password: str = Field(
        min_length=8,
        max_length=72,
        description="Password between 8 characters and 72 bytes (bcrypt limit).",
    )

    @field_validator("username", mode="after")
    @classmethod
    def padronizar_username(cls, value: str) -> str:
        return value.lower()

    @field_validator("password", mode="after")
    @classmethod
    def validar_tamanho_em_bytes(cls, value: str) -> str:
        if len(value.encode()) > 72:
            raise ValueError("Password must be at most 72 bytes.")
        return value


class UserResponse(BaseModel):
    model_config = ConfigDict(
        from_attributes=True,
        json_schema_extra={"examples": [{"id": 1, "username": "ash"}]},
    )

    id: int = Field(description="User id, generated by the database.")
    username: str = Field(description="Username, in lowercase.")


class Token(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "access_token": "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9...",
                    "token_type": "bearer",
                }
            ]
        }
    )

    access_token: str = Field(description="JWT to send in the Authorization header.")
    token_type: str = Field(default="bearer", description="Always 'bearer'.")
