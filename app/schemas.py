from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.models import Type


class PokemonCreate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "id": 6,
                    "name": "Charizard",
                    "height": 17,
                    "weight": 905,
                    "types": ["Fire", "Flying"],
                    "sprites": "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/6.png",
                }
            ]
        }
    )

    id: int = Field(
        ge=1,
        description="Pokédex number. Chosen by the client, not generated by the database.",
    )
    name: str = Field(
        min_length=2,
        max_length=20,
        description="Pokémon name. Stored in lowercase.",
    )
    height: int = Field(
        ge=0,
        description="Height in decimetres (17 = 1.7 m), same unit used by the PokéAPI.",
    )
    weight: int = Field(
        ge=0,
        description="Weight in hectograms (905 = 90.5 kg), same unit used by the PokéAPI.",
    )
    types: list[str] = Field(
        min_length=1,
        max_length=2,
        description="One or two type names. Stored in lowercase; existing types are reused.",
    )
    sprites: str = Field(
        max_length=255,
        description="URL of the Pokémon's front sprite image.",
    )

    @field_validator("types", mode="after")
    @classmethod
    def padronizar_tipos(cls, value):
        value = [i.lower() for i in value]
        return value

    @field_validator("name", mode="after")
    @classmethod
    def padronizar_nome(cls, value):
        return value.lower()


class PokemonUpdate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {"weight": 950},
                {"types": ["Fire", "Dragon"]},
            ]
        }
    )

    name: str | None = Field(
        default=None,
        min_length=2,
        max_length=20,
        description="New name. Must not belong to another Pokémon.",
    )
    height: int | None = Field(
        default=None, ge=0, description="New height in decimetres."
    )
    weight: int | None = Field(
        default=None, ge=0, description="New weight in hectograms."
    )
    types: list[str] | None = Field(
        default=None,
        min_length=1,
        max_length=2,
        description="New list of types. Replaces the current list entirely.",
    )
    sprites: str | None = Field(
        default=None, max_length=255, description="New sprite URL."
    )

    @field_validator("types")
    @classmethod
    def padronizar_tipos(cls, value):
        if not value:
            return value
        value = [i.lower() for i in value]
        return value

    @field_validator("name")
    @classmethod
    def padronizar_nome(cls, value):
        if not value:
            return value
        return value.lower()


class PokemonResponse(BaseModel):
    model_config = ConfigDict(
        from_attributes=True,
        json_schema_extra={
            "examples": [
                {
                    "id": 6,
                    "name": "charizard",
                    "height": 17,
                    "weight": 905,
                    "types": ["fire", "flying"],
                    "sprites": "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/6.png",
                }
            ]
        },
    )

    id: int = Field(description="Pokédex number.")
    name: str = Field(description="Pokémon name, in lowercase.")
    height: int = Field(description="Height in decimetres.")
    weight: int = Field(description="Weight in hectograms.")
    types: list[str] = Field(description="Type names, in lowercase.")
    sprites: str = Field(description="URL of the front sprite image.")

    @field_validator("types", mode="before")
    @classmethod
    def extrai_nomes_dos_tipos(cls, value):
        return [i.name if isinstance(i, Type) else i for i in value]


class ErrorResponse(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={"examples": [{"detail": "Pokémon not found"}]}
    )

    detail: str = Field(description="Human-readable error message.")


class UserCreate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={"examples": [{"username": "ash", "password": "pikachu123"}]}
    )

    username: str = Field(
        min_length=3,
        max_length=50,
        description="Unique username. Stored in lowercase.",
    )
    password: str = Field(
        min_length=8,
        max_length=72,
        description="Password between 8 characters and 72 bytes (bcrypt limit).",
    )

    @field_validator("username", mode="after")
    @classmethod
    def padronizar_username(cls, value):
        return value.lower()

    @field_validator("password", mode="after")
    @classmethod
    def validar_tamanho_em_bytes(cls, value):
        if len(value.encode()) > 72:
            raise ValueError("Password must be at most 72 bytes.")
        return value


class UserResponse(BaseModel):
    model_config = ConfigDict(
        from_attributes=True,
        json_schema_extra={"examples": [{"id": 1, "username": "ash"}]},
    )

    id: int = Field(description="User id, generated by the database.")
    username: str = Field(description="Username, in lowercase.")


class Token(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "access_token": "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9...",
                    "token_type": "bearer",
                }
            ]
        }
    )

    access_token: str = Field(description="JWT to send in the Authorization header.")
    token_type: str = Field(default="bearer", description="Always 'bearer'.")
